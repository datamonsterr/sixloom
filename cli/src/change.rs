//! Change records: the changelog stack under spec/changes/.

use anyhow::{bail, Context, Result};
use regex::Regex;
use std::fs;
use std::path::{Path, PathBuf};

use crate::catalog::{frontmatter_field, pack_file};

pub const DIR: &str = "spec/changes";
pub const STATUSES: &[&str] = &[
    "proposed", "accepted", "specced", "tested", "built", "rejected",
];

#[derive(Debug, Clone)]
pub struct Change {
    pub id: String,
    pub title: String,
    pub kind: String,
    pub status: String,
    pub affects: String,
    pub raised_at: String,
    pub path: PathBuf,
}

pub fn list(root: &Path) -> Result<Vec<Change>> {
    let dir = root.join(DIR);
    let mut out = vec![];
    if !dir.is_dir() {
        return Ok(out);
    }
    for e in fs::read_dir(&dir)? {
        let p = e?.path();
        if p.extension().is_none_or(|x| x != "md") {
            continue;
        }
        let text = fs::read_to_string(&p)?;
        let f = |k: &str| frontmatter_field(&text, k).unwrap_or_default();
        out.push(Change {
            id: f("id"),
            title: f("title"),
            kind: f("kind"),
            status: f("status"),
            affects: f("affects").replace('\n', " "),
            raised_at: f("raised_at"),
            path: p,
        });
    }
    out.sort_by(|a, b| a.id.cmp(&b.id));
    Ok(out)
}

fn slug(s: &str) -> String {
    let mut out = String::new();
    for c in s.to_lowercase().chars() {
        if c.is_ascii_alphanumeric() {
            out.push(c);
        } else if !out.ends_with('-') {
            out.push('-');
        }
    }
    out.trim_matches('-').chars().take(48).collect()
}

pub fn create(root: &Path, title: &str, kind: &str, affects: &[String]) -> Result<PathBuf> {
    if !["feedback", "bug", "sync", "test"].contains(&kind) {
        bail!("kind must be feedback, bug, sync or test");
    }
    let next = list(root)?
        .iter()
        .filter_map(|c| c.id.strip_prefix("CH-").and_then(|n| n.parse::<u32>().ok()))
        .max()
        .unwrap_or(0)
        + 1;
    let id = format!("CH-{next:04}");
    let tpl = pack_file("core/skills/sxl-patch/CHANGE.template.md")?;
    let affects = if affects.is_empty() {
        "[]".to_string()
    } else {
        format!("[{}]", affects.join(", "))
    };
    let body = tpl
        .replacen("CH-0000", &id, 1)
        .replacen("<short title>", &title.replace('"', "'"), 1)
        .replacen(
            "feedback        # feedback",
            &format!("{kind}        # feedback"),
            1,
        )
        .replacen("[F-000.AC0]", &affects, 1)
        .replacen(
            "YYYY-MM-DD",
            &chrono::Utc::now().format("%Y-%m-%d").to_string(),
            1,
        );
    let path = root.join(DIR).join(format!("{id}-{}.md", slug(title)));
    fs::create_dir_all(path.parent().unwrap())?;
    fs::write(&path, body)?;
    Ok(path)
}

pub fn set_status(root: &Path, id: &str, status: &str, by: Option<&str>) -> Result<Change> {
    if !STATUSES.contains(&status) {
        bail!("status must be one of: {}", STATUSES.join(", "));
    }
    let c = list(root)?
        .into_iter()
        .find(|c| c.id.eq_ignore_ascii_case(id))
        .with_context(|| format!("no change record {id} in {DIR}"))?;
    let text = fs::read_to_string(&c.path)?;
    let st = Regex::new(r"(?m)^status:\s*\S+").unwrap();
    let mut text = st
        .replace(&text, format!("status: {status}").as_str())
        .into_owned();
    if let Some(by) = by {
        let ab = Regex::new(r"(?m)^approved_by:.*$").unwrap();
        text = ab
            .replace(&text, format!("approved_by: {by}").as_str())
            .into_owned();
    }
    fs::write(&c.path, text)?;
    Ok(Change {
        status: status.into(),
        ..c
    })
}

/// Regenerate spec/CHANGELOG.md from the records.
pub fn render_log(root: &Path) -> Result<PathBuf> {
    let mut md = String::from(
        "# Changelog\n\n<!-- Generated by `sixloom change log` from spec/changes/. Do not edit. -->\n\n\
         | ID | Title | Kind | Status | Affects | Raised |\n|---|---|---|---|---|---|\n",
    );
    for c in list(root)?.iter().rev() {
        let file = c.path.file_name().unwrap().to_string_lossy();
        md.push_str(&format!(
            "| [{}](changes/{file}) | {} | {} | {} | {} | {} |\n",
            c.id, c.title, c.kind, c.status, c.affects, c.raised_at
        ));
    }
    let p = root.join("spec/CHANGELOG.md");
    fs::write(&p, md)?;
    Ok(p)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn create_list_approve_log() {
        let dir = tempfile::tempdir().unwrap();
        let r = dir.path();
        let p = create(
            r,
            "Show archived projects",
            "feedback",
            &["F-002.AC1".into()],
        )
        .unwrap();
        assert!(p.ends_with("CH-0001-show-archived-projects.md"));
        create(r, "Login bug", "bug", &[]).unwrap();
        let all = list(r).unwrap();
        assert_eq!(all.len(), 2);
        assert_eq!(all[0].status, "proposed");
        assert_eq!(all[1].kind, "bug");
        let c = set_status(r, "ch-0001", "accepted", Some("Ada <ada@x.io>")).unwrap();
        assert_eq!(c.status, "accepted");
        assert_eq!(list(r).unwrap()[0].status, "accepted");
        let log = fs::read_to_string(render_log(r).unwrap()).unwrap();
        assert!(log.contains("| [CH-0001](changes/CH-0001-show-archived-projects.md) | Show archived projects | feedback | accepted |"));
    }
}
